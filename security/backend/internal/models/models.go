// PaginationMeta matches GetTalk's standardized pagination contract.
type PaginationMeta struct {
	Limit      int    `json:"limit"`
	Offset     int    `json:"offset"`
	Total      int    `json:"total"`
	HasMore    bool   `json:"hasMore"`
	NextCursor string `json:"nextCursor,omitempty"`
}

// PaginatedResult wraps list responses consistently with GetTalk's API conventions.
type PaginatedResult[T any] struct {
	Items      []T            `json:"items"`
	Data       []T            `json:"data"`
	Limit      int            `json:"limit"`
	Offset     int            `json:"offset"`
	Total      int            `json:"total"`
	HasMore    bool           `json:"hasMore"`
	NextCursor string         `json:"nextCursor,omitempty"`
	Pagination PaginationMeta `json:"pagination"`
}

// NewPaginatedResult constructs a standardized PaginatedResult.
func NewPaginatedResult[T any](items []T, limit, offset, total int, nextCursor string) PaginatedResult[T] {
	if items == nil {
		items = []T{}
	}
	hasMore := offset+len(items) < total
	meta := PaginationMeta{
		Limit:      limit,
		Offset:     offset,
		Total:      total,
		HasMore:    hasMore,
		NextCursor: nextCursor,
	}
	return PaginatedResult[T]{
		Items:      items,
		Data:       items,
		Limit:      limit,
		Offset:     offset,
		Total:      total,
		HasMore:    hasMore,
		NextCursor: nextCursor,
		Pagination: meta,
	}
}

